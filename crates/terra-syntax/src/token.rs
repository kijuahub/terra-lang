use terra_diagnostics::Span;

#[derive(Clone, Debug)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

#[derive(Clone, Debug)]
pub enum TokenKind {
    Ident(String),
    Int(i64),
    Float(f32),
    Double(f64),
    StringLit(String),
    Class,
    Interface,
    Extends,
    Implements,
    Super,
    SelfKw,
    Override,
    Pub,
    Priv,
    Static,
    Final,
    Const,
    Var,
    Mut,
    Enum,
    Try,
    Exception,
    Throw,
    If,
    Else,
    Match,
    Loop,
    While,
    For,
    In,
    Break,
    Continue,
    Func,
    Return,
    Async,
    Await,
    True,
    False,
    Do,
    Package,
    Use,
    New,
    Delete,
    Null,
    Underscore,
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Dot,
    DotDot,
    Semi,
    Colon,
    Arrow,
    FatArrow,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Eq,
    EqEq,
    Not,
    NotEq,
    Lt,
    Gt,
    Le,
    Ge,
    AndAnd,
    OrOr,
    Eof,
}

impl TokenKind {
    pub fn text(&self) -> String {
        match self {
            TokenKind::Ident(s) => s.clone(),
            TokenKind::Int(n) => n.to_string(),
            TokenKind::Float(n) => format!("{n}f"),
            TokenKind::Double(n) => n.to_string(),
            TokenKind::StringLit(s) => format!("\"{s}\""),
            TokenKind::Class => "class".into(),
            TokenKind::Interface => "interface".into(),
            TokenKind::Extends => "extends".into(),
            TokenKind::Implements => "implements".into(),
            TokenKind::Super => "super".into(),
            TokenKind::SelfKw => "self".into(),
            TokenKind::Override => "override".into(),
            TokenKind::Pub => "pub".into(),
            TokenKind::Priv => "priv".into(),
            TokenKind::Static => "static".into(),
            TokenKind::Final => "final".into(),
            TokenKind::Const => "const".into(),
            TokenKind::Var => "var".into(),
            TokenKind::Mut => "mut".into(),
            TokenKind::Enum => "enum".into(),
            TokenKind::Try => "try".into(),
            TokenKind::Exception => "exception".into(),
            TokenKind::Throw => "throw".into(),
            TokenKind::If => "if".into(),
            TokenKind::Else => "else".into(),
            TokenKind::Match => "match".into(),
            TokenKind::Loop => "loop".into(),
            TokenKind::While => "while".into(),
            TokenKind::For => "for".into(),
            TokenKind::In => "in".into(),
            TokenKind::Break => "break".into(),
            TokenKind::Continue => "continue".into(),
            TokenKind::Func => "func".into(),
            TokenKind::Return => "return".into(),
            TokenKind::Async => "async".into(),
            TokenKind::Await => "await".into(),
            TokenKind::True => "true".into(),
            TokenKind::False => "false".into(),
            TokenKind::Do => "do".into(),
            TokenKind::Package => "package".into(),
            TokenKind::Use => "use".into(),
            TokenKind::New => "new".into(),
            TokenKind::Delete => "delete".into(),
            TokenKind::Null => "null".into(),
            TokenKind::Underscore => "_".into(),
            TokenKind::Semi => ";".into(),
            TokenKind::Eof => "end of file".into(),
            other => format!("{other:?}"),
        }
    }
}
